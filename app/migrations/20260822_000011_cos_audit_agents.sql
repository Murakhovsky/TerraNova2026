    KEY idx_cos_agent_runs_status (status, created_at),
    KEY idx_cos_agent_runs_correlation (organization_id, correlation_id),
    CONSTRAINT chk_cos_agent_runs_confidence CHECK (confidence IS NULL OR (confidence >= 0 AND confidence <= 1))
