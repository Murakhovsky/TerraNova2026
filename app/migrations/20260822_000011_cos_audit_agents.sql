    id VARCHAR(40) NOT NULL,
    organization_id VARCHAR(40) NOT NULL,
    agent_name VARCHAR(160) NOT NULL,
    agent_version VARCHAR(40) NOT NULL,
    provider VARCHAR(80) NOT NULL,
    model VARCHAR(120) NOT NULL,
    prompt_version VARCHAR(40) NOT NULL,
    schema_version VARCHAR(40) NOT NULL,
    subject_type VARCHAR(100) NULL,
    subject_id VARCHAR(100) NULL,
    status ENUM('QUEUED', 'RUNNING', 'COMPLETED', 'FAILED', 'INVALID_OUTPUT') NOT NULL,
    context_reference JSON NULL,
    input_snapshot JSON NULL,
    output JSON NULL,
    confidence DECIMAL(5, 4) NULL,
    input_tokens INT UNSIGNED NULL,
    output_tokens INT UNSIGNED NULL,
    cost_amount DECIMAL(14, 6) NULL,
    cost_currency CHAR(3) NULL,
    duration_ms INT UNSIGNED NULL,
    error TEXT NULL,
    correlation_id VARCHAR(40) NOT NULL,
    started_at DATETIME(6) NULL,
    finished_at DATETIME(6) NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
