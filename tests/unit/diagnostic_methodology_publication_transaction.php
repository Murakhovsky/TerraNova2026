<?php
declare(strict_types=1);
use Domains\Diagnostic\Application\Service\MethodologyStudioService;
use Domains\Diagnostic\Methodology\Serialization\MethodologyPackSerializer;
use Tests\Support\InMemoryMethodologyStudioRepository;
$root=dirname(__DIR__,2);
require $root.'/vendor/autoload.php';
require_once $root.'/tests/Support/InMemoryMethodologyStudioRepository.php';
$repo=new InMemoryMethodologyStudioRepository();
$studio=new MethodologyStudioService($repo);
$org='tenant-a';$pack='sales-studio';$v='0.2.0';
$input=['slug'=>$pack,'name'=>'Sales Diagnostic','domain'=>'Sales','methodology_version'=>$v];
$studio->create($org,$input,'31');
$source=json_decode(file_get_contents($root.'/resources/diagnostic/sales/0.1.0/sales-diagnostic-pack.json'),true,512,JSON_THROW_ON_ERROR);
$map=['sections'=>'AREA','criteria'=>'CRITERION','facts'=>'FACT','metrics'=>'METRIC','questions'=>'QUESTION','evidence_requirements'=>'EVIDENCE_REQUIREMENT','rules'=>'RULE','dependencies'=>'DEPENDENCY','recommendations'=>'RECOMMENDATION','benchmarks'=>'BENCHMARK','scoring'=>'SCORING'];
foreach($map as $key=>$type)foreach($source[$key]??[] as $i=>$entity)$studio->saveEntity($org,$pack,$v,$type,$entity+['order'=>$i],'31');
$check=static function(bool $ok,string $message):void{if(!$ok)throw new RuntimeException($message);};
$reject=static function(callable $call):void{try{$call();}catch(DomainException){return;}throw new RuntimeException('Unsafe Studio mutation allowed.');};
$snapshot=static fn()=>serialize([$repo->packsData,$repo->versionsData,$repo->entityData,$repo->scenarioData,$repo->results,$repo->audits]);
$before=$snapshot();
$reject(fn()=> $studio->publish($org,$pack,$v,'31'));
$check($snapshot()===$before,'Failed publish did not roll back validation and audit.');
$reject(fn()=> $studio->create($org,[...$input,'name'=>'overwrite'],'31'));
$check($snapshot()===$before,'Duplicate pack create mutated data.');
foreach(['0.0.0','0.1.1000','00.2.0'] as $invalid)$reject(fn()=> $studio->clone($org,$pack,$v,$invalid,'31'));
$metrics=[];foreach($source['metrics'] as $m)$metrics[$m['id']]=$m['direction']==='lower_is_better'?10:90;
$facts=array_fill_keys(array_column($source['facts'],'id'),true);
$studio->saveScenario($org,$pack,$v,['id'=>'healthy','name'=>'Healthy','input'=>['facts'=>$facts,'metrics'=>$metrics],'expected'=>['findings'=>[]]],'31');
$hash=(new MethodologyPackSerializer())->hash($studio->compile($org,$pack,$v)->pack);
$studio->publish($org,$pack,$v,'31');
$check($repo->version($org,$pack,$v)['status']==='PUBLISHED' && $repo->version($org,$pack,$v)['content_hash']===$hash,'Published version/hash mismatch.');
$check($repo->pack($org,$pack)['active_methodology_version']===$v,'Activation missing.');
$published=$snapshot();
$studio->publish($org,$pack,$v,'31');
$check($snapshot()===$published,'Replay mutated published version.');
$reject(fn()=> $studio->saveEntity($org,$pack,$v,'FACT',$source['facts'][0],'31'));
$reject(fn()=> $studio->archive($org,$pack,$v,'31'));
$reject(fn()=> $studio->publish('tenant-b',$pack,$v,'31'));
$check($snapshot()===$published,'Rejected mutation changed published state.');
$studio->clone($org,$pack,$v,'0.3.0','31');
$check($repo->version($org,$pack,'0.3.0')['content_hash']===str_repeat('0',64),'Clone inherited stale published fingerprint.');
echo "Methodology publication transaction, rollback, immutable versions and replay PASS.\n";
