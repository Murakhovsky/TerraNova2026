#!/usr/bin/env python3
"""Product P7 evidence packaging/validation. Never approves, deploys or changes readiness."""
import argparse
import datetime as dt
import json
import os
import re
import subprocess
import sys
from pathlib import Path
from urllib.parse import urlsplit

SHA = re.compile(r"^[0-9a-f]{40}$")
HEX32 = re.compile(r"^[0-9a-f]{32}$")
TENANT = re.compile(r"^[a-zA-Z0-9][a-zA-Z0-9._:-]{0,39}$")
SCENARIOS = ("D3", "D4", "D5")
ENGINEERING_CHECKS = ("Federation MySQL", "runtime", "Capital Markets Pack")
REQUIRED_PIPELINES = ("CI", "Documentation", "Frontend", "Runtime")

def valid_url(value):
    if not isinstance(value, str):
        return False
    url = urlsplit(value)
    return url.scheme == "https" and bool(url.hostname) and not url.username and not url.password

def utc_now():
    return dt.datetime.now(dt.timezone.utc).isoformat()

def evidence_time(value):
    try:
        stamp = dt.datetime.fromisoformat(value)
        return stamp.tzinfo is not None and stamp <= dt.datetime.now(dt.timezone.utc) + dt.timedelta(minutes=5)
    except (TypeError, ValueError):
        return False

def engineering():
    """Only invoked after all Runtime dependency jobs succeed. PR merge SHA != branch SHA."""
    if os.environ.get("GITHUB_ACTIONS") != "true":
        raise ValueError("Engineering packet must be generated by GitHub Actions.")
    repo = os.environ["GITHUB_REPOSITORY"]
    sha = subprocess.check_output(["git", "rev-parse", "HEAD"], text=True).strip()
    candidate = os.environ.get("PRODUCT_CANDIDATE_SHA") or os.environ["GITHUB_SHA"]
    if not SHA.fullmatch(sha) or not SHA.fullmatch(candidate) or sha != os.environ["GITHUB_SHA"]:
        raise ValueError("Revision mismatch.")
    return {
        "schema": "product_management.engineering_acceptance.v1",
        "domain": "product_management", "status": "ENGINEERING_PASS",
        "candidate_sha": candidate, "tested_revision_sha": sha,
        "environment": "disposable_ci", "performed_at": utc_now(),
        "checks": list(ENGINEERING_CHECKS),
        "evidence_url": f"https://github.com/{repo}/actions/runs/{os.environ['GITHUB_RUN_ID']}",
        "fixture_llm": True, "shopify_mock": True,
        "independent_release_approval": False,
    }

def validate(packet, sha, shopify):
    errors = []
    def require(condition, label):
        if not condition:
            errors.append(label)
    engineering_packet = packet.get("engineering", {})
    require(engineering_packet.get("schema") == "product_management.engineering_acceptance.v1"
            and engineering_packet.get("domain") == "product_management"
            and engineering_packet.get("tested_revision_sha") == sha
            and engineering_packet.get("status") == "ENGINEERING_PASS"
            and engineering_packet.get("checks") == list(ENGINEERING_CHECKS)
            and engineering_packet.get("environment") == "disposable_ci"
            and evidence_time(engineering_packet.get("performed_at"))
            and valid_url(engineering_packet.get("evidence_url")), "exact_release_revision_engineering_evidence")
    pipelines = packet.get("pipelines", [])
    if not isinstance(pipelines, list) or not all(isinstance(row, dict) for row in pipelines):
        pipelines = []
    require(sorted(str(row.get("name")) for row in pipelines) == sorted(REQUIRED_PIPELINES)
            and all(row.get("tested_revision_sha") == sha and row.get("conclusion") == "success"
                    and valid_url(row.get("evidence_url")) and evidence_time(row.get("performed_at"))
                    for row in pipelines), "full_exact_revision_CI_documentation_frontend_runtime")
    attestation = packet.get("deployment", {})
    require(attestation.get("revision_sha") == sha
            and all(isinstance(attestation.get(key), str) and bool(re.fullmatch(r"[0-9a-f]{64}", attestation[key]))
                    for key in ("execution_source_sha256", "routes_sha256"))
            and valid_url(attestation.get("evidence_url"))
            and evidence_time(attestation.get("performed_at")), "commit_bound_deployment_evidence")
    rows = packet.get("independent_acceptance", [])
    if not isinstance(rows, list) or not all(isinstance(row, dict) for row in rows):
        rows = []
    require(len(rows) == 3 and sorted(str(row.get("stage")) for row in rows) == list(SCENARIOS), "D3_D4_D5_required_once")
    by_stage = {row.get("stage"): row for row in rows if row.get("stage") in SCENARIOS}
    for stage in SCENARIOS:
        row = by_stage.get(stage, {})
        tenant, operator, reviewer = row.get("tenant"), row.get("operator"), row.get("independent_reviewer")
        require(row.get("revision_sha") == sha and row.get("result") == "PASS"
                and isinstance(tenant, str) and bool(TENANT.fullmatch(tenant))
                and row.get("environment") == ("production" if stage == "D5" else "staging")
                and isinstance(row.get("scenario"), str) and bool(row["scenario"].strip())
                and isinstance(operator, str) and bool(operator.strip())
                and isinstance(reviewer, str) and bool(reviewer.strip()) and reviewer != operator
                and isinstance(row.get("business_readback"), list) and bool(row["business_readback"])
                and all(isinstance(ref, str) and bool(ref.strip()) for ref in row["business_readback"])
                and valid_url(row.get("evidence_url")) and evidence_time(row.get("performed_at")),
                f"{stage}_independent_business_evidence")
    require(by_stage.get("D3", {}).get("tenant") == by_stage.get("D4", {}).get("tenant")
            and by_stage.get("D3", {}).get("tenant") != by_stage.get("D5", {}).get("tenant"), "isolated_staging_tenant")
    d5 = by_stage.get("D5", {})
    require(d5.get("alerting_verified") is True and d5.get("rollback_or_disable_verified") is True, "D5_alerting_and_rollback")
    live = packet.get("live_ai", {})
    require(live.get("revision_sha") == sha and live.get("environment") == "staging"
            and live.get("tenant") == by_stage.get("D3", {}).get("tenant")
            and live.get("status") == "NATIVE_AI_READBACK_PASS"
            and all(isinstance(live.get(key), str) and bool(live[key]) for key in
                    ("intent_id", "goal_id", "plan_id", "run_id", "evaluation_id", "provider", "model"))
            and isinstance(live.get("llm_usage_id"), str) and bool(HEX32.fullmatch(live["llm_usage_id"]))
            and not re.search(r"fixture|mock|stub|fake|test", str(live.get("provider")) + " " + str(live.get("model")), re.I)
            and live.get("stock_reconciliation") == "OK"
            and isinstance(live.get("business_readback"), list) and bool(live["business_readback"])
            and valid_url(live.get("evidence_url")) and evidence_time(live.get("performed_at")), "P6_live_ai_native_readback")
    if shopify:
        provider = packet.get("shopify", {})
        require(provider.get("revision_sha") == sha and provider.get("result") == "PASS"
                and provider.get("tenant") == d5.get("tenant")
                and provider.get("stages") == ["S1", "S2", "S3", "S4", "S5"]
                and valid_url(provider.get("evidence_url")) and evidence_time(provider.get("performed_at"))
                and isinstance(provider.get("independent_reviewer"), str) and bool(provider["independent_reviewer"].strip())
                and isinstance(provider.get("operator"), str) and bool(provider["operator"].strip())
                and provider.get("independent_reviewer") != provider.get("operator")
                and isinstance(provider.get("business_readback"), list) and bool(provider["business_readback"]),
                "optional_shopify_live_acceptance")
    return {"status": "BLOCKED" if errors else "EVIDENCE_COMPLETE_FOR_INDEPENDENT_REVIEW",
            "revision_sha": sha, "scope": "native_plus_shopify" if shopify else "native",
            "blockers": errors, "release_authorized": False, "passport_updated": False}

def main():
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest="mode", required=True)
    sub.add_parser("engineering")
    verify = sub.add_parser("verify")
    verify.add_argument("--revision", required=True)
    verify.add_argument("--evidence", type=Path, required=True)
    verify.add_argument("--include-shopify", action="store_true")
    args = parser.parse_args()
    try:
        if args.mode == "engineering":
            result = engineering()
        else:
            if not SHA.fullmatch(args.revision) or args.evidence.stat().st_size > 128_000:
                raise ValueError("Invalid bounded revision/evidence.")
            result = validate(json.loads(args.evidence.read_text()), args.revision, args.include_shopify)
        print(json.dumps(result, ensure_ascii=False, indent=2))
        return 1 if result["status"] == "BLOCKED" else 0
    except (ValueError, TypeError, KeyError, AttributeError, OSError, subprocess.CalledProcessError):
        print(json.dumps({"status": "BLOCKED", "blockers": ["invalid_or_missing_evidence"], "release_authorized": False}))
        return 1

if __name__ == "__main__":
    sys.exit(main())
